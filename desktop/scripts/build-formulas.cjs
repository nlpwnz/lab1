const fs=require('node:fs'),path=require('node:path'),katex=require('katex');
const formulas={
  units:String.raw`y=y_{\min}+\frac{p}{100}\left(y_{\max}-y_{\min}\right)`,
  graph:String.raw`v_{\text{ср}}=\frac{\Delta\theta}{\Delta t}=\frac{\theta_B-\theta_A}{t_B-t_A}`
};
const rendered=Object.fromEntries(Object.entries(formulas).map(([key,tex])=>[key,katex.renderToString(tex,{displayMode:true,throwOnError:true,output:'htmlAndMathml',trust:false})]));
const output='// Generated by scripts/build-formulas.cjs. Uses the bundled course KaTeX CSS and fonts.\nwindow.TauBasicsFormulas='+JSON.stringify(rendered)+';\n';
const target=path.join(__dirname,'../content/tau/basics-formulas.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==output)throw Error('Run npm run build:formulas and commit the generated file.');}
else fs.writeFileSync(target,output);
console.log('Validated and rendered',Object.keys(formulas).length,'offline formulas.');
